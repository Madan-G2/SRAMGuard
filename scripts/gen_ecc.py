#!/usr/bin/env python3
"""Generate the Hsiao (72,64) SECDED H matrix.

Emits
  rtl/sg_ecc_pkg.sv      -- column table + encode/syndrome functions used by sg_ecc
  tb/sg_ecc_ref_pkg.sv   -- independent row-mask reference model for the testbench

Both files come from the same column list, so RTL and model cannot drift apart.

Columns (codeword bit i):
  0..55   all C(8,3)=56 weight-3 columns
  56..63  8 weight-5 columns (rotations of 00011111) -> every H row has weight 26
  64..71  identity (weight 1) = check bits
"""
import itertools, os

cols = []
for combo in itertools.combinations(range(8), 3):
    cols.append(sum(1 << b for b in combo))
for r in range(8):
    m = 0x1F
    cols.append(((m << r) | (m >> (8 - r))) & 0xFF)
for k in range(8):
    cols.append(1 << k)

assert len(cols) == 72 and len(set(cols)) == 72
assert all(bin(c).count("1") % 2 == 1 for c in cols), "Hsiao: every column odd weight"
row_w = [sum((c >> k) & 1 for c in cols) for k in range(8)]
assert len(set(row_w)) == 1, row_w

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

with open(os.path.join(root, "rtl", "sg_ecc_pkg.sv"), "w") as f:
    f.write("// GENERATED by scripts/gen_ecc.py -- do not edit\n")
    f.write("// Hsiao (72,64): 56 weight-3 + 8 weight-5 data columns, identity check columns.\n")
    f.write(f"// Row weight (all 8 rows): {row_w[0]}\n")
    f.write("package sg_ecc_pkg;\n")
    f.write("  localparam logic [7:0] H_COL [0:71] = '{\n")
    for i, c in enumerate(cols):
        f.write(f"    8'h{c:02x}" + ("," if i < 71 else "") + f"  // bit {i}\n")
    f.write("  };\n\n")
    f.write("  function automatic logic [7:0] ecc_enc(input logic [63:0] d);\n")
    f.write("    logic [7:0] c;\n    c = '0;\n")
    f.write("    for (int i = 0; i < 64; i++) if (d[i]) c ^= H_COL[i];\n")
    f.write("    return c;\n  endfunction\n\n")
    f.write("  function automatic logic [7:0] ecc_syn(input logic [71:0] cw);\n")
    f.write("    return ecc_enc(cw[63:0]) ^ cw[71:64];\n  endfunction\nendpackage\n")

with open(os.path.join(root, "tb", "sg_ecc_ref_pkg.sv"), "w") as f:
    f.write("// GENERATED by scripts/gen_ecc.py -- do not edit\n")
    f.write("// Reference model: per-syndrome-bit row masks (independent of sg_ecc_pkg code).\n")
    f.write("package sg_ecc_ref_pkg;\n")
    f.write("  localparam logic [71:0] H_ROW [0:7] = '{\n")
    for k in range(8):
        m = sum(((cols[i] >> k) & 1) << i for i in range(72))
        f.write(f"    72'h{m:018x}" + ("," if k < 7 else "") + f"  // syndrome bit {k}\n")
    f.write("  };\n")
    f.write("  function automatic logic [7:0] ref_syn(input logic [71:0] cw);\n")
    f.write("    logic [7:0] s;\n    for (int k = 0; k < 8; k++) s[k] = ^(cw & H_ROW[k]);\n    return s;\n  endfunction\n")
    f.write("  function automatic logic [71:0] ref_encode(input logic [63:0] d);\n")
    f.write("    logic [71:0] cw; logic [7:0] s;\n    cw = {8'h00, d};\n    s = ref_syn(cw);\n")
    f.write("    return {s, d};\n  endfunction\nendpackage\n")

print("row weights:", row_w, "-> generated sg_ecc_pkg.sv, sg_ecc_ref_pkg.sv")
