#!/usr/bin/env python3
"""Derive the B2 and B3 synthesis tops from rtl/sg_top.sv (B4) without touching the verified RTL.

  B2 = B1 + power-on MBIST + BIRA + repair, no online engine:
       sg_scrub and sg_win (and the segment buffer inside it) are removed and their outputs tied off,
       so the arbiter's window/repair hooks see constants and are pruned by the synthesis tool.
  B3 = B2 + scrub-only online:
       full online engine present, but TEST_EN, ONLINE_REPAIR_EN and the March SS escalation are tied
       to 0, i.e. the capture + ECC write-back path only.

Every substitution is checked, so a change in sg_top.sv that breaks the pattern fails loudly.
"""
import os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, "..", "..", "rtl", "sg_top.sv")).read()


def sub1(text, pat, rep, flags=0):
    new, n = re.subn(pat, rep, text, count=1, flags=flags)
    if n != 1:
        sys.exit(f"gen_builds: pattern not found: {pat!r}")
    return new


def drop_instance(text, mod, inst):
    return sub1(text, rf"^  {mod} {inst} \(.*?^  \);\n", "", re.M | re.S)


# ---------------------------------------------------------------- B2
b2 = sub1(src, r"^module sg_top$", "module sg_top_b2", re.M)
b2 = drop_instance(b2, "sg_scrub", "u_scrub")
b2 = drop_instance(b2, "sg_win", "u_win")
ties = """
  // ---- B2: no online engine; every output of sg_scrub / sg_win is a constant
  assign sc_base = '0;          assign sc_go = 1'b0;          assign sc_sweep_done = 1'b0;
  assign sc_ovr = 1'b0;
  assign win_idle = 1'b1;       assign win_open = 1'b0;       assign win_base = '0;
  assign win_mb_start = 1'b0;   assign win_mb_ack = 1'b0;     assign win_mb_alg = '0;
  assign w_valid = 1'b0;        assign w_cmd = '0;            assign w_tag = '0;
  assign f_valid = 1'b0;        assign f_pend = 1'b0;         assign f_idx = '0;
  assign f_ref = '0;            assign f_pol = 1'b0;
  assign remap_set_en = 1'b0;   assign remap_set_k = 1'b0;    assign remap_set_row = '0;
  assign win_ins_v = 1'b0;      assign win_ins_row = '0;      assign win_ins_mask = '0;
  assign sw_req = 1'b0;         assign rd_act = 1'b0;         assign rd_row = '0;  assign rd_k = 1'b0;
  assign ev_ce = 1'b0;          assign ev_ce_row = '0;        assign ev_ue_w = 1'b0;
  assign ev_df = 1'b0;          assign ev_hard = 1'b0;        assign ev_trans = 1'b0;
  assign ev_win_done = 1'b0;    assign ev_repair = 1'b0;      assign ev_rep_row = '0;
  assign ev_repair_fail = 1'b0;
"""
b2 = sub1(b2, r"(  // -+ RESET_TEST / MAINT\n)", ties + r"\n\1")
b2 = "// GENERATED by syn/builds/gen_builds.py from rtl/sg_top.sv -- do not edit\n" + b2

# ---------------------------------------------------------------- B3
b3 = sub1(src, r"^module sg_top$", "module sg_top_b3", re.M)
b3 = sub1(b3, r"^  cfg_t cfg;\n",
          "  cfg_t cfg_raw, cfg;\n"
          "  // B3: scrub-only online: no transparent March, no online repair\n"
          "  always_comb begin\n"
          "    cfg = cfg_raw;\n"
          "    cfg.test_en = 1'b0;\n"
          "    cfg.online_repair_en = 1'b0;\n"
          "  end\n", re.M)
b3 = sub1(b3, r"\.cfg\(cfg\), \.maint_req\(maint_req\)", ".cfg(cfg_raw), .maint_req(maint_req)")
b3 = sub1(b3, r"\.ovr\(sc_ovr\)", ".ovr()")
b3 = sub1(b3, r"^  logic online_en;\n", "  logic online_en;\n  assign sc_ovr = 1'b0;   // no March SS escalation in scrub-only\n", re.M)
b3 = "// GENERATED by syn/builds/gen_builds.py from rtl/sg_top.sv -- do not edit\n" + b3

open(os.path.join(here, "sg_top_b2.sv"), "w").write(b2)
open(os.path.join(here, "sg_top_b3.sv"), "w").write(b3)
print("generated sg_top_b2.sv, sg_top_b3.sv")
